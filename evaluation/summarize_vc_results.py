#!/usr/bin/env python3
"""
summarize_vc_results.py

Scan a variant_calling_sweep.py output directory for vc_* subdirectories,
extract TP/FP/FN from isec results, count retained reads, and generate
a summary CSV + formatted comparison table.

Usage:
  python summarize_vc_results.py --dir ./ --output summary.csv

Expected directory structure (auto-generated by variant_calling_sweep.py):
  outdir/
    truth.norm.gz           (pre-normalized truth)
    vc_NONE_xxxxxxxx/       (baseline)
      filtered.bam
      calls.vcf
      calls.norm.gz
      isec/0000.vcf         (FP: calls-only)
      isec/0001.vcf         (FN: truth-only)
      isec/0002.vcf         (TP: shared)
    vc_MAPQ_10_xxxxxxxx/
      ...
    vc_ROQ_20_xxxxxxxx/
      ...
    vc_COMBINED_20_xxxxxxxx/
      ...

Output:
  1. CSV file with all conditions
  2. Formatted summary table (MAPQ vs ROQ comparison)
  3. Optional: --compare-only prints just the comparison table
"""
import argparse
import os
import re
import subprocess
import sys
import pandas as pd

SAMTOOLS = os.environ.get('SAMTOOLS', 'samtools')
BCFTOOLS = os.environ.get('BCFTOOLS', 'bcftools')


def run(cmd):
    r = subprocess.run(cmd, shell=True, capture_output=True, text=True)
    if r.returncode != 0:
        print(f"  WARN: {cmd} → {r.stderr.strip()[:200]}", file=sys.stderr)
    return r.stdout.strip()


def count_vcf_records(vcf_path):
    """Count non-header lines in a VCF file."""
    if not os.path.exists(vcf_path):
        return 0
    out = run(f"{BCFTOOLS} view {vcf_path} | grep -v '^#' | wc -l")
    return int(out) if out else 0


def count_reads_bam(bam_path):
    """Count reads in a BAM file."""
    if not os.path.exists(bam_path):
        return 0
    out = run(f"{SAMTOOLS} view -c {bam_path}")
    return int(out) if out else 0


def count_variants_vcf(vcf_path):
    """Count variants in a VCF (handles both .vcf and .vcf.gz)."""
    if not os.path.exists(vcf_path):
        return 0
    if vcf_path.endswith('.gz'):
        out = run(f"{BCFTOOLS} view {vcf_path} | grep -v '^#' | wc -l")
    else:
        out = run(f"grep -v '^#' {vcf_path} | wc -l")
    return int(out) if out else 0


def parse_dirname(dirname):
    """Parse 'vc_MAPQ_20_abc123' → ('MAPQ', 20).
    Parse 'vc_NONE_abc123' → ('NONE', 0).
    Parse 'vc_COMBINED_30_abc123' → ('COMBINED', 30).
    """
    m = re.match(r'vc_(NONE)_', dirname)
    if m:
        return 'NONE', 0
    m = re.match(r'vc_(MAPQ|ROQ|COMBINED)_(\d+)_', dirname)
    if m:
        return m.group(1), int(m.group(2))
    return None, None


def scan_directory(indir):
    """Scan for vc_* subdirectories and collect metrics."""
    results = []

    for entry in sorted(os.listdir(indir)):
        if not entry.startswith('vc_'):
            continue
        subdir = os.path.join(indir, entry)
        if not os.path.isdir(subdir):
            continue

        ftype, threshold = parse_dirname(entry)
        if ftype is None:
            continue

        # Count reads from filtered.bam
        filt_bam = os.path.join(subdir, 'filtered.bam')
        n_reads = count_reads_bam(filt_bam)

        # Count TP/FP/FN from isec
        isec_dir = os.path.join(subdir, 'isec')
        fp = count_vcf_records(os.path.join(isec_dir, '0000.vcf'))
        fn = count_vcf_records(os.path.join(isec_dir, '0001.vcf'))
        tp = count_vcf_records(os.path.join(isec_dir, '0002.vcf'))

        # Count total called variants
        calls_norm = os.path.join(subdir, 'calls.norm.gz')
        n_variants = count_variants_vcf(calls_norm)

        # Compute metrics
        prec = tp / (tp + fp) if (tp + fp) > 0 else 0
        rec = tp / (tp + fn) if (tp + fn) > 0 else 0
        f1 = 2 * prec * rec / (prec + rec) if (prec + rec) > 0 else 0

        results.append({
            'filter_type': ftype,
            'threshold': threshold,
            'n_reads': n_reads,
            'n_variants': n_variants,
            'tp': tp,
            'fp': fp,
            'fn': fn,
            'precision': round(prec, 4),
            'recall': round(rec, 4),
            'f1': round(f1, 4),
        })
        print(f"  {entry}: {ftype:>9} T={threshold:>2}  "
              f"reads={n_reads:>8}  TP={tp:>6} FP={fp:>6} FN={fn:>6}  "
              f"prec={prec:.4f} rec={rec:.4f} F1={f1:.4f}")

    return results


def print_summary(df, n_total_reads=None):
    """Print formatted MAPQ vs ROQ comparison table."""
    print("\n" + "=" * 90)
    print("SUMMARY: MAPQ vs ROQ")
    print("=" * 90)

    # Baseline
    none_rows = df[df.filter_type == 'NONE']
    if not none_rows.empty:
        n = none_rows.iloc[0]
        print(f"\nBaseline (NONE):  reads={n.n_reads}  variants={n.n_variants}  "
              f"TP={n.tp} FP={n.fp} FN={n.fn}  prec={n.precision} rec={n.recall} F1={n.f1}")

    # Get common thresholds
    mapq_ts = sorted(df[df.filter_type == 'MAPQ'].threshold.unique())
    roq_ts = sorted(df[df.filter_type == 'ROQ'].threshold.unique())
    common_ts = sorted(set(mapq_ts) & set(roq_ts))

    if not common_ts:
        print("\nNo common thresholds between MAPQ and ROQ to compare.")
        return

    # Header
    print(f"\n{'T':>4} {'MAPQ_FP':>8} {'ROQ_FP':>8} {'FP_red':>8} {'FP_%':>7} "
          f"{'MAPQ_F1':>8} {'ROQ_F1':>8} {'dF1':>7} "
          f"{'MAPQ_ret':>9} {'ROQ_ret':>9} {'dRet':>7}")
    print("-" * 90)

    for t in common_ts:
        m = df[(df.filter_type == 'MAPQ') & (df.threshold == t)]
        r = df[(df.filter_type == 'ROQ') & (df.threshold == t)]
        if m.empty or r.empty:
            continue
        m = m.iloc[0]
        r = r.iloc[0]
        fp_red = m.fp - r.fp
        fp_pct = 100 * fp_red / m.fp if m.fp > 0 else 0
        d_f1 = r.f1 - m.f1
        m_ret = m.n_reads / n_total_reads if n_total_reads else 0
        r_ret = r.n_reads / n_total_reads if n_total_reads else 0
        d_ret = r_ret - m_ret
        print(f"{t:>4} {m.fp:>8} {r.fp:>8} {fp_red:>8} {fp_pct:>6.1f}% "
              f"{m.f1:>8.4f} {r.f1:>8.4f} {d_f1:>+7.4f} "
              f"{m_ret:>9.4f} {r_ret:>9.4f} {d_ret:>+7.4f}")

    # COMBINED if present
    comb_df = df[df.filter_type == 'COMBINED']
    if not comb_df.empty:
        print(f"\n--- COMBINED (MAPQ AND ROQ) ---")
        print(f"{'T':>4} {'FP':>8} {'F1':>8} {'reads':>10} {'retention':>10}")
        print("-" * 50)
        for _, c in comb_df.sort_values('threshold').iterrows():
            ret = c.n_reads / n_total_reads if n_total_reads else 0
            print(f"{c.threshold:>4} {c.fp:>8} {c.f1:>8.4f} {c.n_reads:>10} {ret:>10.4f}")

    # All conditions table
    print(f"\n--- ALL CONDITIONS ---")
    print(f"{'Filter':>10} {'T':>4} {'reads':>10} {'TP':>7} {'FP':>7} {'FN':>7} "
          f"{'prec':>7} {'rec':>7} {'F1':>7}")
    print("-" * 75)
    for _, row in df.sort_values(['filter_type', 'threshold']).iterrows():
        print(f"{row.filter_type:>10} {row.threshold:>4} {row.n_reads:>10} "
              f"{row.tp:>7} {row.fp:>7} {row.fn:>7} "
              f"{row.precision:>7.4f} {row.recall:>7.4f} {row.f1:>7.4f}")


def main():
    ap = argparse.ArgumentParser(
        description='Summarize variant_calling_sweep.py results from subdirectories.')
    ap.add_argument('--dir', required=True,
                    help='Directory containing vc_* subdirectories')
    ap.add_argument('--output', default='summary.csv',
                    help='Output CSV filename (default: summary.csv)')
    ap.add_argument('--total-reads', type=int, default=None,
                    help='Total reads in region (for retention rate). '
                         'If not given, uses NONE baseline read count.')
    args = ap.parse_args()

    if not os.path.isdir(args.dir):
        print(f"ERROR: {args.dir} is not a directory", file=sys.stderr)
        sys.exit(1)

    print(f"Scanning {args.dir} for vc_* subdirectories...\n")
    results = scan_directory(args.dir)

    if not results:
        print("No vc_* subdirectories found.", file=sys.stderr)
        sys.exit(1)

    df = pd.DataFrame(results)

    # Determine total reads for retention rate
    n_total = args.total_reads
    if n_total is None:
        none_rows = df[df.filter_type == 'NONE']
        if not none_rows.empty:
            n_total = none_rows.iloc[0].n_reads
            print(f"\nUsing NONE baseline read count as total: {n_total}")
        else:
            # Use max read count as proxy
            n_total = df.n_reads.max()
            print(f"\nNo NONE baseline found. Using max read count as total: {n_total}")

    # Add retention_rate
    df['retention_rate'] = (df.n_reads / n_total).round(4)

    # Save CSV
    outpath = os.path.join(args.dir, args.output) if not os.path.isabs(args.output) else args.output
    df.to_csv(outpath, index=False)
    print(f"\nCSV saved to {outpath}")

    # Print summary
    print_summary(df, n_total)


if __name__ == '__main__':
    main()
